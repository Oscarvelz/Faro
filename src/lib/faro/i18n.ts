export function translate(lang: Lang, key: string): string {
  const pack = lang === "en" ? en : es;
  return pack[key] ?? es[key] ?? key;
}

export function monthName(lang: Lang, month: number, short = false): string {
  const d = new Date(2026, month - 1, 1);
  return new Intl.DateTimeFormat(lang === "en" ? "en-US" : "es-NI", {
    month: short ? "short" : "long",
  }).format(d);
}

/** Activity entries are stored as the commit's detail (an internal id, a fixed Spanish phrase, or the user's own line name).
 *  Show them as words in the reader's language; the user's own names stay as they wrote them. */
const AUDIT_IDS: Record<string, string> = {
  goal: "audit.goal", green: "audit.green", yellow: "audit.yellow", months: "audit.months", keys: "audit.keys",
  Vista: "audit.view", "Vista de moneda": "audit.view", up: "audit.structure", down: "audit.structure", hide: "audit.structure", move: "audit.structure",
  "delete cat": "audit.delcat", look: "audit.look", color: "audit.look", icon: "audit.look", order: "audit.order",
  presets: "audit.presets", "ni-banks": "audit.banks", "Muestra de agosto": "audit.sample",
};
const TEMPLATES = ["soltero", "familia", "estudiante", "negocio"];
export function auditLabel(lang: Lang, detail: string): string {
  const d = (detail || "").trim();
  if (AUDIT_IDS[d]) return translate(lang, AUDIT_IDS[d]);
  if (TEMPLATES.includes(d)) return translate(lang, "audit.template").replace("{x}", translate(lang, `tpl.${d}`));
  let m = /^Atajo (.+)$/.exec(d);
  if (m) return translate(lang, "audit.shortcut").replace("{x}", translate(lang, `key.${m[1]}`));
  m = /^Tasa manual (.+)$/.exec(d);
  if (m) return translate(lang, "audit.rateManual").replace("{x}", m[1]);
  m = /^Tasa (.+)$/.exec(d);
  if (m) return translate(lang, "audit.rate").replace("{x}", m[1]);
  m = /^(Agregar|Editar) (.+)$/.exec(d);
  if (m) return translate(lang, m[1] === "Agregar" ? "audit.add" : "audit.edit").replace("{x}", m[2]);
  return d;
}

/** A keyboard shortcut's action as words (falls back to the id for an unknown action). */
export function shortcutLabel(lang: Lang, action: string): string {
  return translate(lang, `key.${action}`);
}

/**
 * Faro manual — the single source of truth for every (?) bubble and every manual entry.
 *
 * A bubble shows `what` of its topic, word for word. The manual shows the same `what`
 * under "Qué es" (and `whatAlt` right after it), so the two can never disagree.
 * Exception: a topic may carry a short `bubble` text of its own, written only for the (?)
 * (quick help goes straight to the point; the depth stays in the manual's `what`).
 * Every text is a pair [español, English].
 *
 * Writing rules: plain, short sentences. One-line `sum` first. Never name another app.
 * `[[Término]]` inside a text is a link to that place in the app (see links.ts).
 * Chapters follow the app's screens, in the app's order.
 */

export type L = readonly [string, string];

/** A place in Faro. Maps 1:1 to provider state (section / vault tab / overlay). */
export type Screen =
  | "top" //        the bar at the top (on every screen)
  | "desk" //       Central
  | "cobros" //     Central → Cobros panel (opened on the Pagos lens corner)
  | "income" //     Libros → Ingresos
  | "fixed" //      Libros → Fijos
  | "variable" //   Libros → Variables
  | "shops" //      Libros → Compras
  | "subs" //       Libros → Cuotas
  | "vault-save" // Libros → Ahorros
  | "vault-meta" // Libros → Meta
  | "vault-retiro"
  | "vault-emergencia"
  | "vault-owed" // Libros → Me deben (Deudas row)
  | "vault-owe" //  Libros → Debo (Cuotas · Préstamos)
  | "stats" //      Estudio → Estudio
  | "advice" //     Estudio → Asesor
  | "tools" //      Mesa de cambio (sheet on phone, aside on wide screens)
  | "settings"; //  Ajustes

export type Go = {
  screen: Screen;
  /** data-anchor of the element to scroll to and glow, when the topic's own (?) is not visible. */
  anchor?: string;
  /** Fold to open first (Ajustes fold id, Estudio card id, or any element listening to `faro-open`). */
  fold?: string;
  /** Central lens to pick first. */
  lens?: "have" | "spend" | "debt";
  /** Where it is, said plainly ("Central, arriba"). */
  where: L;
};

export type Topic = {
  id: string;
  title: L;
  /** One line: what this is for. Read first. */
  sum: L;
  /**
   * "tip": light, self-evident — its (?) shows only the bubble.
   * "manual": needs context — the bubble adds "Más en el manual →", and the entry must extend the bubble (how / tip).
   */
  depth: "tip" | "manual";
  /** What it is. Also the exact text of the (?) bubble. 1–2 sentences. */
  what: L;
  /** Second text, when the same (?) changes with the state (shown after `what` in the manual). */
  whatAlt?: L;
  /** Short bubble-only text, for topics whose `what` is the manual's full "Qué es": the (?) shows
   * this instead, brief and to the point. Absent on almost every topic — their bubbles show `what`. */
  bubble?: L;
  how?: L;
  tip?: L;
  go?: Go;
  /** Extra words for the A–Z index and the search. The title is always indexed. */
  terms?: L[];
  /**
   * i18n keys this topic documents (bookkeeping, not shown). Most are UI LABELS and stay in i18n.
   * Only explanatory texts (tip.*, *.help*, pot.total.*, pot.save.*, pot.avg.line, desk.savings.from.*,
   * study.*.note) retire once their bubble reads from this topic — see PLAN.md §6.
   */
  keys?: string[];
};


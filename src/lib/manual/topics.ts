export type Numbered = Topic & { num: string; chapter: Chapter };

export const MANUAL_TOPICS: Numbered[] = MANUAL_CHAPTERS.flatMap((chapter, ci) =>
  chapter.topics.map((topic, ti) => ({ ...topic, num: `${ci + 1}.${ti + 1}`, chapter })),
);

const BY_ID = new Map(MANUAL_TOPICS.map((t) => [t.id, t]));

/** Renamed ids keep working (old deep links, old <Hint topic>). Empty on day one. */
const ALIASES: Record<string, string> = {};

export function findTopic(id: string | undefined | null): Numbered | null {
  if (!id) return null;
  return BY_ID.get(id) ?? BY_ID.get(ALIASES[id] ?? "") ?? null;
}

export function pick(lang: string, pair: L): string {
  return lang === "en" ? pair[1] : pair[0];
}

/** Bubble text: `what`, or `whatAlt` when the caller says the alternate state is on. */
export function bubbleText(topic: Topic, lang: string, alt = false): string {
  return pick(lang, alt && topic.whatAlt ? topic.whatAlt : topic.what);
}

/** Plain text of a topic for search ([[ ]] stripped). */
export function topicText(topic: Topic, lang: string): string {
  return [topic.title, topic.sum, topic.what, topic.whatAlt, topic.how, topic.tip, topic.go?.where, ...(topic.terms ?? [])]
    .filter(Boolean)
    .map((pair) => pick(lang, pair as L))
    .join(" ")
    .replace(/\[\[|\]\]/g, "");
}

export type IndexTerm = { term: string; topics: Numbered[] };

/** A–Z index: every title and listed term, one line per word, sorted the Spanish (or English) way. */
export function alphaIndex(lang: string): { letter: string; items: IndexTerm[] }[] {
  const byTerm = new Map<string, IndexTerm>();
  for (const topic of MANUAL_TOPICS) {
    const title = pick(lang, topic.title);
    for (const pair of [topic.title, ...(topic.terms ?? [])]) {
      const term = pick(lang, pair);
      if (pair !== topic.title && title.toLowerCase().startsWith(term.toLowerCase())) continue;
      const key = term.toLowerCase();
      const row = byTerm.get(key) ?? { term, topics: [] };
      if (!row.topics.includes(topic)) row.topics.push(topic);
      byTerm.set(key, row);
    }
  }
  const all = [...byTerm.values()];
  for (const row of all) row.topics.sort((a, b) => a.num.localeCompare(b.num, undefined, { numeric: true }));
  const coll = new Intl.Collator(lang === "en" ? "en" : "es", { sensitivity: "base", ignorePunctuation: true });
  const lead = (s: string) => s.replace(/^[¿¡$@"'(+\s−/-]+/, "");
  all.sort((a, b) => coll.compare(lead(a.term), lead(b.term)));
  const groups: { letter: string; items: IndexTerm[] }[] = [];
  for (const item of all) {
    const first = lead(item.term).charAt(0).toLocaleUpperCase(lang === "en" ? "en" : "es");
    const letter = /[0-9]/.test(first) ? "#" : first === "Ñ" ? "Ñ" : first.normalize("NFD").replace(/[\u0300-\u036f]/g, "") || "#";
    const last = groups[groups.length - 1];
    if (last && last.letter === letter) last.items.push(item);
    else groups.push({ letter, items: [item] });
  }
  return groups;
}


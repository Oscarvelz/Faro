#!/usr/bin/env python3
"""Stamp the app version into src/lib/faro/build-version.ts from public/sw.js.

public/sw.js's VERSION is the single source of truth for the release number.
build.sh runs this before every vite build, so the bundle (and the version
line at the bottom of Ajustes) can never carry a number that disagrees with
the service worker shipping it. version.test.ts is the tripwire: it fails if
the stamped file and sw.js ever disagree.
"""
import io
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

sw = io.open(os.path.join(ROOT, "public", "sw.js"), encoding="utf8").read()
m = re.search(r'VERSION\s*=\s*"faro-([0-9]+\.[0-9]+\.[0-9]+)"', sw)
if not m:
    sys.exit('stamp-version: no VERSION = "faro-X.Y.Z" found in public/sw.js')
version = m.group(1)
out = (
    "// GENERATED by tools/stamp-version.py (run by build.sh) from public/sw.js.\n"
    "// sw.js's VERSION is the single source of truth — never edit this by hand;\n"
    "// version.test.ts fails if the two ever disagree.\n"
    f'export const FARO_VERSION = "{version}";\n'
)
path = os.path.join(ROOT, "src", "lib", "faro", "build-version.ts")
io.open(path, "w", encoding="utf8").write(out)
print(f"stamp-version: FARO_VERSION = {version}")
